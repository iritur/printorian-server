#!/usr/bin/env bash
# Generated-artifact protection for printorian-server (ZCode PreToolUse hook).
#
# Protocol: read the tool payload JSON from stdin, extract
# tool_input.file_path, and decide. Exit 0 = allow. Exit 2 = block; stderr is
# shown to the calling agent. Any parse failure exits 0 — a broken guard must
# not become a broken editor.
#
# Protected paths and how to regenerate each:
#   repo/x86_64/            the pacman repository — repo-add produces the
#                           .db/.files and packages land here from builds;
#                           regenerate with repo-add, never by hand
#   pkgs/*/src/, pkgs/*/pkg/  makepkg workdirs (sources, packaged trees)
#   *.pkg.tar.zst, *.pkg.tar.xz   built packages (also *.sig)
#   iso/                    generated ISO images (the ISO builder script)
#   psrv-probe-report.json  output of the probe tool (rerun the tool)
#
# All of these are produced through Bash, which this hook deliberately does
# not match. It only stops hand edits of the artifacts.

set -u

payload="$(cat)"

path="$(printf '%s' "$payload" | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    print("")
    sys.exit(0)
value = data.get("tool_input", {}).get("file_path", "") or ""
print(value.replace("\\", "/"))
' 2>/dev/null || true)"

if [ -z "$path" ]; then
  exit 0
fi

case "$path" in
  */repo/x86_64/*|repo/x86_64/*)
    echo "Blocked: '$path' is the pacman repository — repo-add manages the db and packages land here from builds. Regenerate with repo-add (see .zcode/skills/psrv-build/SKILL.md), do not hand-edit." >&2
    exit 2
    ;;
  */pkgs/*/src/*|*/pkgs/*/pkg/*|pkgs/*/src/*|pkgs/*/pkg/*)
    echo "Blocked: '$path' is a makepkg workdir (sources/packaged tree) — regenerated on every build. Edit the PKGBUILD beside it instead." >&2
    exit 2
    ;;
  *.pkg.tar.zst|*.pkg.tar.xz|*.pkg.tar.gz|*.pkg.tar.zst.sig|*.pkg.tar.xz.sig)
    echo "Blocked: '$path' is a built package (or its signature) — rebuild it with makepkg/devtools, do not edit it." >&2
    exit 2
    ;;
  */iso/*|iso/*)
    echo "Blocked: '$path' is under iso/ — images are generated by the ISO builder tool. Change the builder, not the image." >&2
    exit 2
    ;;
  *psrv-probe-report.json|psrv-probe-report.json)
    echo "Blocked: '$path' is the probe tool's output — rerun the probe (tools/), do not edit the report." >&2
    exit 2
    ;;
esac

exit 0
